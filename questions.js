const concepts = Object.fromEntries(Object.entries(source).map(([subject, rows]) => [subject,
  rows.split('\n').map((row, index) => {
    const [topic, term, definition] = row.split('|');
    return { id: `${subject}-${index + 1}`, subject, topic, term, definition };
  })]));

const shuffle = (items, random = Math.random) => {
  const copy = [...items];
  for (let i = copy.length - 1; i > 0; i--) {
    const j = Math.floor(random() * (i + 1));
    [copy[i], copy[j]] = [copy[j], copy[i]];
  }
  return copy;
};

export const BANK = Object.fromEntries(Object.entries(concepts).map(([subject, entries]) => {
  const items = entries.flatMap((entry, index) => {
    const distractors = [7, 13, 23].map(offset => entries[(index + offset) % entries.length]);
    const explanation = `${entry.term}：${entry.definition}。`;
    return [
      { id: `${entry.id}-definition`, subject, topic: entry.topic,
        prompt: `下列何者最符合「${entry.term}」的定義？`,
        options: [entry.definition, ...distractors.map(item => item.definition)], correct: 0, explanation },
      { id: `${entry.id}-term`, subject, topic: entry.topic,
        prompt: `「${entry.definition}」指的是哪個概念？`,
        options: [entry.term, ...distractors.map(item => item.term)], correct: 0, explanation },
    ];
  });
  return [subject, items];
}));

export const TRACKS = {
  basic: { name: '初級｜綜合模擬考', subjects: ['basic', 'genai'], split: [25, 25], badge: '初級' },
  data: { name: '中級｜數據分析', subjects: ['planning', 'data'], split: [25, 25], badge: '中級 A' },
  ml: { name: '中級｜機器學習', subjects: ['planning', 'ml'], split: [25, 25], badge: '中級 B' },
};

export function makeExam(track) {
  const config = TRACKS[track];
  if (!config) throw new Error('未知考試類別');
  const chosen = config.subjects.flatMap((subject, index) => {
    // Pick at most one form of a concept per exam, avoiding obvious repeats.
    const pool = shuffle(concepts[subject]);
    return pool.slice(0, config.split[index]).map(concept => {
      const form = Math.random() < 0.5 ? 'definition' : 'term';
      const original = BANK[subject].find(q => q.id === `${concept.id}-${form}`);
      const options = shuffle(original.options.map((value, optionIndex) => ({ value, optionIndex })));
      return { ...original, options: options.map(option => option.value),
        correct: options.findIndex(option => option.optionIndex === original.correct) };
    });
  });
  return shuffle(chosen);
}

export const BANK_SIZE = Object.values(BANK).reduce((total, items) => total + items.length, 0);
